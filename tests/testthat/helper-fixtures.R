# Stata reference results (data-raw/stata_fixtures.do, apexog
# v0.21.1, StataNow 19.5), converted by data-raw/make_fixtures.R.
fx <- readRDS(test_path("fixtures", "stata_fixtures.rds"))
fxdat <- fx$data

# The R call reproducing each Stata specification.  For LTZ specs `dr` is the
# matrix of gamma draws in the spec's gunits (Stata stores the latent draws in
# e(gamma_sim); the tests undo the conversion with Stata's own m_phi or
# sigma_tilde).
fx_calls <- list(
  A1 = function() apexog(y ~ x1 + x2, endog = d ~ z1, data = fxdat,
                         gmin = -0.1, gmax = 0.1, grid = 5, verbose = FALSE),
  A3 = function() apexog(y ~ x1 + x2 + factor(cat), endog = d ~ z1 + z2, data = fxdat,
                         gmin = -0.05, gmax = 0.05, grid = 3, verbose = FALSE),
  A5 = function() apexog(y ~ x1m + x2, endog = d ~ z1, data = fxdat, subset = x3 > -1.5,
                         gmin = -0.05, gmax = 0.05, grid = 3, verbose = FALSE),
  # Stata cannot take an empty control list; its A6 uses a constant control,
  # which it omits as collinear, i.e. a no-controls model.
  A6 = function() apexog(y ~ 1, endog = d ~ z1, data = fxdat,
                         gmin = -0.1, gmax = 0.1, grid = 3, verbose = FALSE),
  B1 = function() apexog(yb ~ x1 + x2, endog = db ~ z1 + zb, data = fxdat,
                         firststage = "probit", gmin = -0.1, gmax = 0.1, grid = 3,
                         verbose = FALSE),
  B2 = function() apexog(yf ~ x1, endog = df ~ z1, data = fxdat, firststage = "fprobit",
                         gmin = -0.1, gmax = 0.1, grid = 5, verbose = FALSE),
  B3 = function() apexog(yc ~ x1, endog = dc ~ z1, data = fxdat, firststage = "poisson",
                         gmin = -0.1, gmax = 0.1, grid = 5, verbose = FALSE),
  B4 = function() apexog(ym ~ x1, endog = list(db ~ z1 + zb, d2 ~ z2 + zb), data = fxdat,
                         firststage = c("probit", "linear"), gmin = -0.05, gmax = 0.05,
                         grid = 3, verbose = FALSE),
  B5 = function() apexog(y ~ x1 + x2, endog = d ~ z1, data = fxdat, cluster = ~team,
                         gmin = -0.1, gmax = 0.1, grid = 3, verbose = FALSE),
  B6 = function() apexog(ym2 ~ x1, endog = d + d2 ~ z1 + z2 + zb, data = fxdat,
                         cfinteract = TRUE, gmin = -0.05, gmax = 0.05, grid = 2,
                         verbose = FALSE),
  B8 = function() apexog(ym ~ x1, endog = list(db ~ z1 + zb, d2 ~ z2 + zb), data = fxdat,
                         firststage = c("probit", "linear"), cfinteract = TRUE,
                         gmin = -0.05, gmax = 0.05, grid = 2, verbose = FALSE),
  B7 = function() apexog(y ~ x1 + x2, endog = d ~ z1, data = fxdat, cluster = "teams",
                         gmin = -0.1, gmax = 0.1, grid = 3, verbose = FALSE),
  C1 = function() apexog(yx ~ x1 + x3, endog = d ~ z1, data = fxdat, aie = c("x1", "x3"),
                         gmin = -0.1, gmax = 0.1, grid = 3, verbose = FALSE),
  C2 = function() apexog(yi ~ x1 + x2, endog = d ~ z1, data = fxdat, aie = c("d", "x2"),
                         gmin = -0.1, gmax = 0.1, grid = 3, verbose = FALSE),
  C3 = function() apexog(ybb ~ x1 + x2, endog = db ~ z1 + zb, data = fxdat,
                         firststage = "probit", aie = c("x2", "db"),
                         gmin = -0.1, gmax = 0.1, grid = 3, verbose = FALSE),
  C3b = function() apexog(yi ~ x1 + x2, endog = d ~ z1, data = fxdat, aie = c("x2", "d"),
                          gmin = -0.1, gmax = 0.1, grid = 3, verbose = FALSE),
  C4 = function() apexog(yx2 ~ x1 + x3, endog = d + d:x3 ~ z1 + z1:x3, data = fxdat,
                         aie = c("d", "x3"), gmin = -0.05, gmax = 0.05, grid = 3,
                         verbose = FALSE),
  C5 = function() apexog(yi ~ x1 + x2, endog = d + d:x2 ~ z1 + z1:x2, data = fxdat,
                         aie = c("d", "x2"), aie_binary = c(FALSE, TRUE),
                         gmin = -0.05, gmax = 0.05, grid = 3, verbose = FALSE),
  C6 = function() apexog(yi ~ x1 + x2, endog = d + d:x2 ~ z1 + z1:x2, data = fxdat,
                         aie = c("d", "x2"), aie_binary = c(FALSE, FALSE),
                         gmin = -0.05, gmax = 0.05, grid = 3, verbose = FALSE),
  C7 = function() apexog(ym ~ x1, endog = list(db ~ z1 + zb, d2 ~ z2 + zb), data = fxdat,
                         firststage = c("probit", "linear"), target = "d2",
                         gmin = -0.05, gmax = 0.05, grid = 3, verbose = FALSE),
  D1 = function() apexog(yb ~ x1 + x2, endog = db ~ z1 + zb, data = fxdat,
                         firststage = "biprobit", gmin = -0.1, gmax = 0.1, grid = 3,
                         verbose = FALSE),
  D2 = function() apexog(yb ~ x1 + x2, endog = db ~ z1 + zb, data = fxdat,
                         firststage = "biprobit", cluster = ~team, gmin = 0, gmax = 0,
                         grid = 2, verbose = FALSE),
  E1 = function() apexog(yb ~ x1 + x2, endog = db ~ z1 + zb, data = fxdat,
                         firststage = "probit", gunits = "pr", gmin = -0.02, gmax = 0.02,
                         grid = 3, verbose = FALSE),
  E6 = function() apexog(y ~ x1 + x2, endog = d ~ z1, data = fxdat, gunits = "structural",
                         gmin = -0.1, gmax = 0.1, grid = 3, level = 90, verbose = FALSE),
  A2 = function(dr) apexog(y ~ x1 + x2, endog = d ~ z1, data = fxdat, method = "ltz",
                           draws = dr, verbose = FALSE),
  E2 = function(dr) apexog(y ~ x1 + x2, endog = d ~ z1, data = fxdat, method = "ltz",
                           gunits = "structural", draws = dr, verbose = FALSE),
  E3 = function(dr) apexog(y ~ x1 + x2, endog = d ~ z1 + z2, data = fxdat, method = "ltz",
                           draws = dr, verbose = FALSE),
  E4 = function(dr) apexog(yx2 ~ x1 + x3, endog = d + d:x3 ~ z1 + z1:x3, data = fxdat,
                           aie = c("d", "x3"), method = "ltz", draws = dr, verbose = FALSE),
  E5 = function(dr) apexog(yb ~ x1 + x2, endog = db ~ z1 + zb, data = fxdat,
                           firststage = "biprobit", gunits = "pr", method = "ltz",
                           draws = dr, verbose = FALSE)
)
